# Function with age parameter
def age(year):
    print("Your age is", year)

age(17)


# Function to find square
def square(num):
    print("The square is", num * num)

square(5)


# Function with two parameters
def student(name, age):
    print("Name:", name)
    print("Age:", age)

student("Thanush", 17)